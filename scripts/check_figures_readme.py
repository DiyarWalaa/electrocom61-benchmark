"""
check_figures_readme.py -- fail loudly if figures/README.md has been corrupted

WHY THIS EXISTS

A LaTeX block in figures/README.md was silently corrupted once. The section
was generated by piping a Python program through a shell heredoc; the shell
collapsed a doubled backslash, and Python then read the result as an escape
sequence:

    "\\\\begin{figure}"   intended
    "\\begin{figure}"     after the shell ate one backslash
    "\\x08egin{figure}"   after Python read \\b as BACKSPACE

`\\b` is a VALID Python escape, so nothing warned. The file looked right in a
terminal, because a backspace is invisible, and would have failed to compile
with an error pointing nowhere near the cause.

The other control sequences in the same block survived untouched -- `\\c`,
`\\e`, `\\i` and `\\l` are not valid escapes, so Python leaves them alone and
emits a SyntaxWarning. That is the trap: `\\begin` is the one command in a
figure environment that is silently destroyed rather than loudly preserved.

THE RULE THIS ENFORCES

Generate LaTeX with Python file I/O. Never through a shell heredoc. This
script is the backstop for when that rule is forgotten.

WHAT IT CHECKS

  1. No control characters anywhere in the file, other than newline and tab.
  2. Every ```latex fence is closed.
  3. Every figure environment has a matching \\begin{figure} and \\end{figure}.
  4. Every figure environment carries an \\includegraphics, a \\caption and a
     \\label.
  5. Every \\includegraphics names a file that exists in figures/.

Exits non-zero on any failure, so it can gate a commit.

Run with no arguments:

    python scripts/check_figures_readme.py
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ec61  # noqa: E402


README = os.path.join(ec61.REPO_ROOT, "figures", "README.md")
FIG_DIR = os.path.join(ec61.REPO_ROOT, "figures")

# Newline and tab are the only control characters a Markdown file should hold.
ALLOWED_CONTROL = {"\n", "\t", "\r"}


def main():
    if not os.path.isfile(README):
        sys.stderr.write("not found: %s\n" % README)
        return 1

    with open(README, "r", encoding="utf-8", newline="") as fh:
        text = fh.read()

    failures = []

    # --- 1. control characters --------------------------------------------
    for i, ch in enumerate(text):
        if ord(ch) < 32 and ch not in ALLOWED_CONTROL:
            line = text.count("\n", 0, i) + 1
            ctx = text[max(0, i - 30):i + 30].replace("\n", " ")
            failures.append(
                "control character U+%04X at line %d -- context: %r"
                % (ord(ch), line, ctx))
    if not failures:
        print("  [PASS] no stray control characters")

    # --- 2. fenced latex blocks -------------------------------------------
    fences = re.findall(r"```latex\n(.*?)```", text, re.DOTALL)
    n_open = text.count("```latex")
    if len(fences) != n_open:
        failures.append("%d ```latex fences opened but %d closed"
                        % (n_open, len(fences)))
    else:
        print("  [PASS] %d latex block(s), all fences closed" % len(fences))

    # --- 3-5. figure environments -----------------------------------------
    #
    # Counted INSIDE the fenced blocks only. The prose in this README discusses
    # \begin{figure} by name, and a global count treats that mention as an
    # unclosed environment -- which it did on the first run of this check.
    # Documentation about a LaTeX command is not LaTeX.
    fenced = "\n".join(fences)
    n_begin = len(re.findall(r"\\begin\{figure\*?\}", fenced))
    n_end = len(re.findall(r"\\end\{figure\*?\}", fenced))
    if n_begin != n_end:
        failures.append("inside latex blocks, \\begin{figure} appears %d times "
                        "but \\end{figure} %d times" % (n_begin, n_end))
    elif n_begin == 0:
        failures.append("no figure environments found at all -- expected the "
                        "README to carry LaTeX snippets")
    else:
        print("  [PASS] %d figure environment(s), begin/end balanced" % n_begin)

    for idx, block in enumerate(fences, 1):
        if "\\begin{figure}" not in block and "\\begin{figure*}" not in block:
            failures.append("latex block %d has no \\begin{figure}" % idx)
        for cmd in ("\\includegraphics", "\\caption", "\\label"):
            if cmd not in block:
                failures.append("latex block %d has no %s" % (idx, cmd))
        for path in re.findall(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}",
                               block):
            name = os.path.basename(path)
            if not os.path.isfile(os.path.join(FIG_DIR, name)):
                failures.append("latex block %d references %s, which is not "
                                "in figures/" % (idx, name))
    if not failures:
        print("  [PASS] every block has includegraphics, caption and label, "
              "and every referenced figure exists")

    print()
    if failures:
        print("FAILED -- %d problem(s):" % len(failures))
        for f in failures:
            print("  - %s" % f)
        print()
        print("If a \\begin has become a backspace, the section was almost "
              "certainly generated through a shell heredoc. Regenerate it with "
              "Python file I/O.")
        return 1
    print("figures/README.md is clean.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
